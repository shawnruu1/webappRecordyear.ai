import { createClient } from "@/lib/supabase/server";
import { NextResponse } from "next/server";

// DELETE /api/wins/[id] — soft delete a record.
// Sets deleted_at so the row is retained (recoverable + activity history)
// rather than hard-deleted. RLS scopes wins to the owner; the explicit
// user_id filter is defense-in-depth.
export async function DELETE(
  _request: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params;
  const supabase = await createClient();
  const {
    data: { user },
    error: authError,
  } = await supabase.auth.getUser();

  if (authError || !user) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const { error } = await supabase
    .from("wins")
    .update({ deleted_at: new Date().toISOString() })
    .eq("id", id)
    .eq("user_id", user.id)
    .is("deleted_at", null);

  if (error) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }

  return NextResponse.json({ ok: true });
}
